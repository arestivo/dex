/**
 * The slide palette as TikZ colours. styles/tokens.css is the single source
 * of truth: its `light-dark()` (and plain hex) colour tokens are read and
 * written out as `\definecolor`s, once per theme. Diagrams are compiled
 * once with each palette, so any colour expression works in both themes.
 */

export type DiagramTheme = 'light' | 'dark'
export const DIAGRAM_THEMES: readonly DiagramTheme[] = ['light', 'dark']

/** TikZ colour name → CSS custom property it takes its values from. */
export const DIAGRAM_COLOURS: Readonly<Record<string, string>> = {
  DexInk: 'color-text',
  DexMuted: 'color-muted',
  DexPaper: 'color-bg',
  DexSurface: 'color-surface',
  DexBorder: 'color-border',
  DexAccent: 'color-accent',
  DexAccentSoft: 'tone-info-bg',
  DexInverse: 'color-inverse-bg',
  DexInverseText: 'color-inverse-text',
  DexInfo: 'tone-info',
  DexInfoSoft: 'tone-info-bg',
  DexWarning: 'tone-warning',
  DexWarningSoft: 'tone-warning-bg',
  DexError: 'tone-error',
  DexErrorSoft: 'tone-error-bg',
  DexSuccess: 'tone-success',
  DexSuccessSoft: 'tone-success-bg',
  DexExample: 'tone-example',
  DexExampleSoft: 'tone-example-bg',
}

export interface TokenColour {
  readonly light: string
  readonly dark: string
}

const LIGHT_DARK = /--([\w-]+):\s*light-dark\(\s*#([0-9a-fA-F]{6})\s*,\s*#([0-9a-fA-F]{6})\s*\)/g
const PLAIN = /--([\w-]+):\s*#([0-9a-fA-F]{6})\s*;/g

/** Reads `--name: light-dark(#a, #b)` and `--name: #a;` colour tokens. */
export function parseColourTokens(css: string): Map<string, TokenColour> {
  const tokens = new Map<string, TokenColour>()
  for (const [, name, light, dark] of css.matchAll(LIGHT_DARK)) {
    if (name && light && dark)
      tokens.set(name, { light: light.toUpperCase(), dark: dark.toUpperCase() })
  }
  for (const [, name, value] of css.matchAll(PLAIN)) {
    if (name && value && !tokens.has(name)) {
      tokens.set(name, { light: value.toUpperCase(), dark: value.toUpperCase() })
    }
  }
  return tokens
}

/**
 * The TeX file defining `\ifDexDark` and every `Dex…` colour for one theme.
 * Throws when a colour's token is missing: that is an engine bug.
 */
export function paletteTex(tokens: ReadonlyMap<string, TokenColour>, theme: DiagramTheme): string {
  const lines = [
    '% Generated by Dex from styles/tokens.css. Do not edit.',
    '\\newif\\ifDexDark',
    theme === 'dark' ? '\\DexDarktrue' : '\\DexDarkfalse',
  ]
  for (const [colour, token] of Object.entries(DIAGRAM_COLOURS)) {
    const value = tokens.get(token)
    if (value === undefined)
      throw new Error(`Diagram colour ${colour} needs the CSS token --${token}.`)
    lines.push(`\\definecolor{${colour}}{HTML}{${value[theme]}}`)
  }
  return `${lines.join('\n')}\n`
}
